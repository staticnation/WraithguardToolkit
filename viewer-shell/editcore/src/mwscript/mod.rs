//! Morrowind scripts (MWScript): the compiler the Editor's Script Edit window saves with,
//! and the window's checks. Moved here from `native/src/mwscript` (port step 4.1, slice
//! 5d), which now wraps it for Python.
//!
//! - `compiler`: source to bytecode, a port of MWEdit's compiler, held byte for byte to
//!   MWEdit's own test plugin (`tests/fixtures/mwedit/`, the tests below).
//! - `records`: the load order's records a compile resolves names against, read with the
//!   tes3 crate, plus whatever the patch pool adds.
//! - `check`: the Script Edit window's checks as it is typed (was `mwscript/check.py`).
//! - `listing`: a compiled script read back (the `bytecode` field decoded and
//!   disassembled, was `mwscript/tes3conv.py` and `disassembler.py`).
//! - `flowchart`: a script's control flow as a Mermaid chart (was `mwscript/flowchart.py`).
//! - `data`: MWEdit's grammar and function table, generated by
//!   `tools/gen_mwscript_compiler.py`.
//!
//! `wraithguard/mwscript/compiler.py` is the Python twin, and the fallback when the
//! native module is not built.

pub mod check;
pub mod compiler;
