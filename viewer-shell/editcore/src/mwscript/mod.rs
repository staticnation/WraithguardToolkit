pub mod flowchart;
pub mod listing;
pub mod records;

use std::path::{Path, PathBuf};

use serde_json::Value;

use compiler::{CompileResult, Compiler, CustomFunctions, Levels, Message, default_custom, parse_custom_functions};
use records::{Record, RecordIndex, index_plugins, to_bytes};

/// A record the patch pool adds or changes that a script can name: `(tag, id, script,
/// dial_type, shorts, longs, floats)` (`script` empty and `dial_type` -1 when they do not
/// apply) - `EditorSession.pool_script_records`.
pub type Extra = (String, String, String, i32, Vec<String>, Vec<String>, Vec<String>);

/// Where MWEdit and the MWSE updater put the extended function list.
pub const CUSTOM_FUNCTIONS_FILE: &str = "customfunctions.dat";

/// A `customfunctions.dat` near the load order, read (Windows-1252): beside a plugin, or
/// in the folder above its data folder (the game's, where MWSE's updater writes one).
/// `None` when there is none (the compiler then knows MWEdit's own set).
pub fn find_custom_functions(plugins: &[PathBuf]) -> Option<Vec<u8>> {
    let mut seen: Vec<PathBuf> = Vec::new();
    for plugin in plugins {
        let folder = plugin.parent().unwrap_or(Path::new("")).to_path_buf();
        let up = folder.parent().unwrap_or(Path::new("")).to_path_buf();
        for place in [folder, up] {
            if seen.contains(&place) {
                continue;
            }
            seen.push(place.clone());
            let candidate = place.join(CUSTOM_FUNCTIONS_FILE);
            if candidate.is_file()
                && let Ok(bytes) = std::fs::read(&candidate)
            {
                return Some(bytes);
            }
        }
    }
    None
}

/// The load order's records, read once, to compile any number of scripts against, with
/// the patch pool's records laid over them.
pub struct ScriptCompiler {
    pub index: RecordIndex,
    pub custom: Option<CustomFunctions>,
}

impl ScriptCompiler {
    /// Reads the plugins (earliest first); `extra` is laid over them; `custom` is a
    /// `customfunctions.dat`'s bytes (`None`: the set MWEdit ships).
    pub fn new(plugins: &[PathBuf], extra: &[Extra], custom: Option<&[u8]>) -> ScriptCompiler {
        let mut index = index_plugins(plugins);
        for (tag, id, script, dial_type, shorts, longs, floats) in extra {
            let Ok(rtype) = <[u8; 4]>::try_from(tag.as_bytes()) else { continue };
            let mut rec = Record::new(&rtype, &to_bytes(id));
            rec.script = to_bytes(script);
            rec.dial_type = *dial_type;
            rec.locals = [shorts, longs, floats].map(|v| v.iter().map(|n| to_bytes(n)).collect());
            index.add(rec);
        }
        ScriptCompiler { index, custom: custom.map(parse_custom_functions) }
    }

    /// Compiles source as the plugin's bytes (Windows-1252).
    pub fn run(&self, source: &[u8], levels: &str, tribunal: bool, bloodmoon: bool, extended: bool) -> CompileResult {
        let custom: &CustomFunctions = match &self.custom {
            Some(own) => own,
            None => default_custom(),
        };
        Compiler::with_custom(&self.index, Levels::from_name(levels), tribunal, bloodmoon, custom, extended).compile(source)
    }

    /// Compiles source text with the defaults (all expansions, extended functions).
    pub fn compile_text(&self, text: &str) -> CompileResult {
        self.run(&to_bytes(text), "default", true, true, true)
    }

    /// The locals of a script, or of the script an object carries (a dialogue result's
    /// speaker), as `(shorts, longs, floats)` bytes; `None` when it has none.
    pub fn script_locals(&self, id: &str) -> Option<[Vec<Vec<u8>>; 3]> {
        let rec = self.index.find(&to_bytes(id))?;
        let script = if &rec.rtype == b"SCPT" { rec } else { self.index.find(&rec.script).filter(|_| !rec.script.is_empty())? };
        if &script.rtype != b"SCPT" {
            return None;
        }
        Some(script.locals.clone())
    }

    /// The `SCPT` record a save writes, as the tes3 crate's JSON (the patch's record form),
    /// or `None` when the source does not compile. `text` is kept as given.
    pub fn compile_record(&self, id: &str, text: &str, levels: &str, tribunal: bool, bloodmoon: bool, extended: bool) -> Option<Value> {
        let result = self.run(&to_bytes(text), levels, tribunal, bloodmoon, extended);
        if !result.ok {
            return None;
        }
        let variables = result.var_data();
        let script = tes3::esp::Script {
            id: id.to_string(),
            header: tes3::esp::ScriptHeader {
                num_shorts: result.locals[0].len() as u32,
                num_longs: result.locals[1].len() as u32,
                num_floats: result.locals[2].len() as u32,
                bytecode_length: result.data.len() as u32,
                variables_length: variables.len() as u32,
            },
            variables,
            bytecode: result.data,
            text: text.to_string(),
            ..Default::default()
        };
        serde_json::to_value(tes3::esp::TES3Object::Script(script)).ok()
    }

    /// A dialogue response's result script compiled for its errors, as the Construction
    /// Set checks one on save: the body of a script with the speaker's script's locals
    /// (a result reads and sets them by bare name); the messages' lines are the result's.
    pub fn check_result(&self, text: &str, speaker: &str) -> Vec<Message> {
        let locals = if speaker.is_empty() { None } else { self.script_locals(speaker) };
        let mut head: Vec<String> = vec!["begin _dialogue_result".into()];
        if let Some(locals) = &locals {
            for (kind, names) in ["short", "long", "float"].iter().zip(locals) {
                head.extend(names.iter().map(|n| format!("{kind} {}", records::from_bytes(n))));
            }
        }
        let body = text.replace("\r\n", "\n").replace('\r', "\n");
        let body = body.trim_end_matches('\n');
        let mut lines = head.clone();
        lines.extend([body.to_string(), "end".into(), String::new()]);
        let result = self.compile_text(&lines.join("\n"));
        let (offset, last) = (head.len(), head.len() + body.matches('\n').count() + 1);
        result
            .messages
            .into_iter()
            .filter(|m| m.line > offset)
            .map(|m| Message { line: m.line.min(last) - offset, ..m })
            .collect()
    }
}

/// A compile's messages as the Editor answers them: `{line, level, message}`.
pub fn messages_json(messages: &[Message]) -> Vec<Value> {
    messages.iter().map(|m| serde_json::json!({"line": m.line, "level": m.level, "message": m.text})).collect()
}

impl crate::scripts::Compile for ScriptCompiler {
    fn compile(&self, text: &str) -> crate::scripts::Compiled {
        let r = self.compile_text(text);
        crate::scripts::Compiled { ok: r.ok, messages: messages_json(&r.messages) }
    }
    fn compile_record(&self, key: &str, text: &str) -> Option<Value> {
        ScriptCompiler::compile_record(self, key, text, "default", true, true, true)
    }
}

#[cfg(test)]
mod tests {
    use super::compiler::compile;
    use super::*;
    use crate::frames::{records as frames, subrecords};

    const FIXTURE: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../tests/fixtures/mwedit/MwEditScriptTest.esp");

    /// Each script's SCHD, SCVR, SCDT and SCTX, straight from the file.
    fn scripts(data: &[u8]) -> Vec<[Vec<u8>; 4]> {
        let mut out = Vec::new();
        for (tag, body) in frames(data) {
            if tag != b"SCPT" {
                continue;
            }
            let mut s: [Vec<u8>; 4] = Default::default();
            for (sub, payload) in subrecords(body) {
                let k = match sub {
                    b"SCHD" => 0,
                    b"SCVR" => 1,
                    b"SCDT" => 2,
                    b"SCTX" => 3,
                    _ => continue,
                };
                s[k] = payload.to_vec();
            }
            out.push(s);
        }
        out
    }

    #[test]
    fn matches_mwedit_byte_for_byte() {
        let data = std::fs::read(FIXTURE).expect("the MWEdit test plugin");
        let index = index_plugins(&[PathBuf::from(FIXTURE)]);
        let all = scripts(&data);
        assert_eq!(all.len(), 34);
        let mut wrong = Vec::new();
        for [schd, scvr, scdt, sctx] in &all {
            let r = compile(sctx, &index, Levels::Default, true, true);
            let name = String::from_utf8_lossy(&schd[..schd.iter().position(|&c| c == 0).unwrap_or(32)]).into_owned();
            if !r.ok || &r.data != scdt || &r.var_data() != scvr || &r.header() != schd {
                let at = r.data.iter().zip(scdt).position(|(a, b)| a != b).unwrap_or(r.data.len().min(scdt.len()));
                wrong.push(format!(
                    "{name}: ok={} got {} bytes, want {}, first difference at {at}; {:?}",
                    r.ok,
                    r.data.len(),
                    scdt.len(),
                    r.messages.iter().map(|m| &m.text).collect::<Vec<_>>()
                ));
            }
        }
        assert!(wrong.is_empty(), "{}", wrong.join("\n"));
    }

    #[test]
    fn return_choice_and_globals() {
        let mut index = RecordIndex::default();
        index.add(Record::new(b"GLOB", b"Gx"));
        let r = compile(b"begin r\nreturn\nend\n", &index, Levels::Default, true, true);
        assert_eq!(r.data, b"\x24\x01\x01\x01");
        let r = compile(b"begin c\nChoice \"Yes\", 1, \"No\", 2\nend\n", &index, Levels::Default, true, true);
        let body: &[u8] = b"\"Yes\" 1 \"No\" 2";
        let mut want = vec![0xC9, 0x10, body.len() as u8, 0];
        want.extend_from_slice(body);
        want.extend_from_slice(b"\x01\x01");
        assert_eq!(r.data, want);
        let r = compile(b"begin g\nset gx to 1\nend\n", &index, Levels::Default, true, true);
        assert_eq!(r.data, b"\x05\x01G\x04Gx\x00\x00\x02 1\x01\x01");
    }

    #[test]
    fn extended_functions_from_mwedit_and_from_a_file() {
        let index = RecordIndex::default();
        let src = b"begin t\nXAddItem \"misc_01\", 10\nend\n";
        let r = compile(src, &index, Levels::Default, true, true);
        assert!(r.ok);
        // Arguments pushed last-first, then the opcode (0x3C28).
        assert_eq!(&r.data[..6], &[0x11u8, 0x38, 10, 0, 0, 0]);
        assert_eq!(&r.data[r.data.len() - 4..r.data.len() - 2], &[0x28u8, 0x3C]);
        let custom = parse_custom_functions(b"# c\nfunction\n Name = XMine # x\n Opcode = 0x3999\n Param1 = Long\nend\n");
        assert_eq!(custom[b"xmine".as_slice()].opcode, 0x3999);
        let r = Compiler::with_custom(&index, Levels::Default, true, true, &custom, true).compile(b"begin t\nXMine 5\nend\n");
        assert!(r.ok);
        assert_eq!(r.data, [0x11u8, 0x38, 5, 0, 0, 0, 0x99, 0x39, 0x01, 0x01]);
    }

    #[test]
    fn unknown_ids_follow_the_message_level() {
        let index = RecordIndex::default();
        let src = b"begin u\nnobody->Disable\nend\n";
        assert!(!compile(src, &index, Levels::Default, true, true).ok);
        let weak = compile(src, &index, Levels::Weak, true, true);
        assert!(weak.ok);
        assert!(weak.messages.iter().any(|m| m.level == "warning"));
    }

    #[test]
    fn a_function_after_choice_is_not_inside_it() {
        let index = RecordIndex::default();
        let src = b"begin u\nChoice \"Yes\" 1 \"No\" 2\nGoodbye\nStopCombat\nend\n";
        let got = compile(src, &index, Levels::Default, true, true);
        assert!(!got.messages.iter().any(|m| m.text.contains("within another function")));
    }

    #[test]
    fn a_result_is_checked_with_its_speakers_locals() {
        let mut c = ScriptCompiler::new(&[], &[], None);
        let mut s = Record::new(b"SCPT", b"spk_script");
        s.locals = [vec![b"talked".to_vec()], Vec::new(), Vec::new()];
        c.index.add(s);
        let mut npc = Record::new(b"NPC_", b"spk");
        npc.script = b"spk_script".to_vec();
        c.index.add(npc);
        assert!(c.check_result("set talked to 1", "spk").is_empty());
        let bad = c.check_result("\r\nset nothing_here to 1", "spk");
        assert_eq!(bad.first().map(|m| m.line), Some(2));
    }
}
