/* The markup's own wording, as a table in the page's source: `ui/src/04_tx_markup.js`.

   Each element of the page's markup that names its wording (`data-tx`: its inner HTML,
   `data-txt`: its title, `data-txp`: its placeholder) is the English of that key. The page
   used to read them back out of itself at load (`Text.start`, `Text.builtin`) and put them
   into the page again as HTML, which is what CodeQL's js/xss-through-dom is about: text
   from the page reinterpreted as markup. Read here instead, from the source, once, into a
   literal the page carries.

   The markup is parsed by jsdom, so a key's HTML is what a browser serializes, which is what
   `Text.apply` compares the live element against.

     node gen_tx_markup.js           write ui/src/04_tx_markup.js
     node gen_tx_markup.js --check   fail when it is out of date (the page tests run this) */
'use strict';
const fs = require('fs');
const path = require('path');
const { JSDOM } = require('jsdom');

const UI = path.join(__dirname, '..');
const OUT = path.join(UI, 'src', '04_tx_markup.js');

/** The markup parts of the page, assembled as build.rs assembles them (scripts left out:
 *  they are not run here, and the wording is the markup's). */
function markup() {
  const order = fs.readFileSync(path.join(UI, 'ORDER'), 'utf8').split(/\r?\n/).map(l => l.trim())
    .filter(l => l && !l.startsWith('#') && l.endsWith('.html'));
  let page = order.map(n => fs.readFileSync(path.join(UI, 'src', n), 'utf8')).join('\n');
  const extra = fs.readFileSync(path.join(UI, 'viewer_only.html'), 'utf8');
  const at = page.indexOf('</head>');
  if (at >= 0) page = page.slice(0, at) + extra + page.slice(at);
  return page;
}

function table() {
  const { document } = new JSDOM(markup()).window;
  const norm = s => String(s || '').replace(/\s+/g, ' ').trim();
  const out = {};
  const put = (k, v) => { if (k && out[k] == null) out[k] = v; };
  // In document order, the first element naming a key wins (as Text.start took it).
  for (const el of document.querySelectorAll('[data-tx]')) put(el.dataset.tx, norm(el.innerHTML));
  for (const el of document.querySelectorAll('[data-txt]')) put(el.dataset.txt, el.getAttribute('title') || '');
  for (const el of document.querySelectorAll('[data-txp]')) put(el.dataset.txp, el.getAttribute('placeholder') || '');
  return out;
}

function source(t) {
  const keys = Object.keys(t).sort();
  const lines = keys.map(k => '  ' + JSON.stringify(k) + ': ' + JSON.stringify(t[k]) + ',');
  return '/* GENERATED by ui/tests/gen_tx_markup.js from the page\'s markup (01_head.html, 02_body.html,\n' +
    '   viewer_only.html) - do not edit; run it again after changing a data-tx, data-txt or\n' +
    '   data-txp element. Each key\'s English as the markup has it: data-tx its inner HTML,\n' +
    '   data-txt its title, data-txp its placeholder (05_text.js, Text.start). ' + keys.length + ' keys. */\n' +
    'const TX_MARKUP = {\n' + lines.join('\n') + '\n};\n';
}

if (require.main === module) {
  const want = source(table());
  if (process.argv.includes('--check')) {
    const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (have !== want) { console.error('ui/src/04_tx_markup.js is out of date: run node ui/tests/gen_tx_markup.js'); process.exit(1); }
    console.log('04_tx_markup.js is up to date');
  } else {
    fs.writeFileSync(OUT, want);
    console.log('wrote ' + OUT);
  }
}

module.exports = { table, source, OUT };
