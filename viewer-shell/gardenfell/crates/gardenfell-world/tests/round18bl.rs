#[test]
fn it_places_an_unconstrained_addon_where_openmw_places_it() {
    /* The case that separates OpenMW's algorithm from a layered topological sort, and the
       reason the real one had to be read rather than guessed at. Alphabetically the three
       are `[A_needs_Z, M, Z]`. OpenMW pulls `Z` up to just before its first dependent and
       leaves everything else where its name put it, giving `[Z, A_needs_Z, M]`. Sorting by
       dependency depth would answer `[M, Z, A_needs_Z]` — same constraint honoured,
       different list. */
    let d = Dir::new("omwplace");
    let on_disk = vec![
        ("Base.esm".to_string(), d.plugin("Base.esm", 0)),
        ("Z.omwaddon".to_string(), d.plugin("Z.omwaddon", 0)),
        ("A_needs_Z.omwaddon".to_string(), d.plugin("A_needs_Z.omwaddon", 0)),
        ("M.omwaddon".to_string(), d.plugin("M.omwaddon", 0)),
    ];
    let known = [
        ent("A_needs_Z.omwaddon", &["Base.esm", "Z.omwaddon"]),
        ent("Z.omwaddon", &["Base.esm"]),
        ent("M.omwaddon", &["Base.esm"]),
    ];
    let got = plugins::arrange(&openmw_layout(&d), &s(&["Base.esm"]), &on_disk, &known);
    assert_eq!(got, s(&["Base.esm", "Z.omwaddon", "A_needs_Z.omwaddon", "M.omwaddon"]));
}

