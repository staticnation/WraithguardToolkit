#[test]
fn a_chain_openmws_own_sort_cannot_settle_is_still_loadable() {
    /* The shape that shows `sortFiles` does not always converge: three addons each naming
       only the next, named so that alphabetical order runs against the chain. OpenMW's walk
       answers `[B_Mid, A_Root, C_Top]` — `B_Mid` ahead of the master it rests on — because
       its `moved` guard stops it before it is done. Copying that exactly would put a plugin
       ahead of its master in the order a narrowed run actually parses in, so the walk
       decides placement and a settling pass decides only what it must. */
    let d = Dir::new("omwchain");
    let on_disk = vec![
        ("Base.esm".to_string(), d.plugin("Base.esm", 0)),
        ("C_Top.omwaddon".to_string(), d.plugin("C_Top.omwaddon", 0)),
        ("B_Mid.omwaddon".to_string(), d.plugin("B_Mid.omwaddon", 0)),
        ("A_Root.omwaddon".to_string(), d.plugin("A_Root.omwaddon", 0)),
    ];
    // Named so that name order and load order disagree at every step.
    let known = [
        ent("A_Root.omwaddon", &["Base.esm", "B_Mid.omwaddon"]),
        ent("B_Mid.omwaddon", &["Base.esm", "C_Top.omwaddon"]),
        ent("C_Top.omwaddon", &["Base.esm"]),
    ];
    let got = plugins::arrange(&openmw_layout(&d), &s(&["Base.esm"]), &on_disk, &known);
    let at = |n: &str| got.iter().position(|x| x == n).unwrap();
    assert!(at("C_Top.omwaddon") < at("B_Mid.omwaddon"), "{got:?}");
    assert!(at("B_Mid.omwaddon") < at("A_Root.omwaddon"), "{got:?}");
    assert_eq!(got[0], "Base.esm");
}

