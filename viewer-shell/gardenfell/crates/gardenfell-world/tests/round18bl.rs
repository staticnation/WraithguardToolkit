#[test]
fn masters_come_before_plugins_however_old_they_are() {
    // Morrowind's own rule, and the launcher's: every .esm loads before every .esp.
    let d = Dir::new("vanesm");
    /* `Old.esp` is the oldest file here by a long way. If dates alone decided, it would
       come first; it must not, because Morrowind loads every master before every plugin. */
    let on_disk = vec![
        ("Base.esm".to_string(), d.plugin("Base.esm", 99)),
        ("Old.esp".to_string(), d.plugin("Old.esp", 1)),
        ("Extra.esm".to_string(), d.plugin("Extra.esm", 150)),
    ];
    let got = plugins::arrange(&vanilla_layout(&d), &s(&["Base.esm", "Old.esp"]), &on_disk, &[]);
    assert_eq!(got, s(&["Base.esm", "Extra.esm", "Old.esp"]));
    let at = |n: &str| got.iter().position(|x| x == n).unwrap();
    assert!(at("Extra.esm") < at("Old.esp"), "a master never lands after a plugin: {got:?}");
}

