"""Write the Editor's tables for the Rust side, ``viewer-shell/editcore/data/*.json``.

The tables are generated once, into Python (``wraithguard/patch/field_types.py`` by
``tools/gen_tes3_fieldtypes.py``, ``wraithguard/patch/enum_data.py`` by
``tools/gen_tes3_enums.py``), and what a dialogue condition can be (``workflow.filter_choices``,
from ``wraithguard.esp.enums``). This copies them to JSON for ``editcore::fields``, so both
Editors read one table; ``tests/test_editcore_tables.py`` fails when the two drift (run
this again after either generator). ``opcodes.json`` is the script opcode table the
disassembler reads (``wraithguard/mwscript/opcodes.py``, by ``tools/gen_opcodes.py``).

Run: ``python tools/gen_editcore_tables.py``.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "viewer-shell" / "editcore" / "data" / "fields.json"
OPCODES_OUT = ROOT / "viewer-shell" / "editcore" / "data" / "opcodes.json"


def tables() -> dict[str, object]:
    """The tables, as the JSON holds them."""
    sys.path.insert(0, str(ROOT))
    from wraithguard.patch.enum_data import FIELD_ENUMS
    from wraithguard.patch.field_types import FLAG_VARIANTS, RECORD_FIELDS
    from wraithguard.patch.workflow import filter_choices

    return {
        "_about": "GENERATED by tools/gen_editcore_tables.py from wraithguard/patch/field_types.py "
        "and enum_data.py; do not edit by hand.",
        "record_fields": RECORD_FIELDS,
        "flag_variants": {k: list(v) for k, v in FLAG_VARIANTS.items()},
        "field_enums": {k: list(v) for k, v in FIELD_ENUMS.items()},
        "filter_choices": filter_choices(),
    }


def opcodes() -> dict[str, object]:
    """The script opcode table, as the JSON holds it (by opcode)."""
    sys.path.insert(0, str(ROOT))
    from wraithguard.mwscript.opcodes import EXTENDED, FUNCTIONS, INTERNAL

    return {
        "_about": "GENERATED by tools/gen_editcore_tables.py from wraithguard/mwscript/opcodes.py; "
        "do not edit by hand.",
        "functions": [[op, name, list(params)] for op, (name, params) in sorted(FUNCTIONS.items())],
        "internal": sorted(INTERNAL),
        "extended": sorted(EXTENDED),
    }


def main() -> None:
    """Write the files."""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(tables(), indent=1, sort_keys=True) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
    OPCODES_OUT.write_text(json.dumps(opcodes(), sort_keys=True) + "\n", encoding="utf-8")
    print(f"wrote {OPCODES_OUT}")


if __name__ == "__main__":
    main()
