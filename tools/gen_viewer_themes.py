#!/usr/bin/env python3
"""Regenerate ``viewer-shell/ui/src/19_wg_themes.js``: Wraithguard's themes, in the viewer.

The toolkit's colour themes (``wraithguard/gui/theme.py``'s ``THEME_PRESETS``) become themes
the viewer's Settings > Theme lists beside its own, each worn the way the Wraithguard theme
is: the eleven chrome colours ``chrome_from_theme`` derives, as the ``--wg-*`` properties
``ui/viewer_only.html`` derives the rest of the page from. Generated, so the two lists cannot
drift while Wraithguard's Tk window still exists, and the viewer keeps them when it goes.

Usage::

    python tools/gen_viewer_themes.py          # rewrite the file
    python tools/gen_viewer_themes.py --check  # fail if it is out of date
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

OUT = ROOT / "viewer-shell" / "ui" / "src" / "19_wg_themes.js"

#: Chrome key -> the viewer's property (as ``Themes.wraithguard`` maps them).
PROPS = {
    "bg": "--wg-bg",
    "bg2": "--wg-bg2",
    "field_bg": "--wg-field",
    "border": "--wg-border",
    "fg": "--wg-fg",
    "fg_dim": "--wg-fg-dim",
    "select": "--wg-select",
    "btn_bg": "--wg-btn",
    "btn_bg_active": "--wg-btn-active",
    "accent": "--wg-accent",
    "log_bg": "--wg-log",
}


def on_accent(hex_color: str) -> str:
    """Dark text on a light accent, white on a dark one (as ``Themes.wraithguard``)."""
    h = hex_color.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    rgb = [int(h[i : i + 2], 16) / 255 for i in (0, 2, 4)]
    lin = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in rgb]
    lum = 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2]
    return "#1b1b1b" if lum > 0.179 else "#ffffff"


def slug(name: str) -> str:
    """The theme code a preset name gets."""
    return "wg-" + re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def render() -> str:
    """The generated file."""
    try:
        import tkinter as tk  # noqa: F401 - theme.py imports it; only its data is read here
    except ImportError:  # a machine without Tk can still regenerate this file
        import types

        stub = types.ModuleType("tkinter")
        stub.ttk = types.ModuleType("tkinter.ttk")  # type: ignore[attr-defined]
        stub.font = types.ModuleType("tkinter.font")  # type: ignore[attr-defined]
        sys.modules.update({"tkinter": stub, "tkinter.ttk": stub.ttk, "tkinter.font": stub.font})
    from wraithguard.gui.theme import THEME_PRESETS, chrome_from_theme

    themes = []
    for name, preset in THEME_PRESETS.items():
        chrome = chrome_from_theme(preset)
        props = {PROPS[k]: v for k, v in chrome.items() if k in PROPS}
        props["--wg-on-accent"] = on_accent(chrome["accent"])
        themes.append({"code": slug(name), "label": name, "props": props})
    data = json.dumps(themes, indent=1, ensure_ascii=False)
    return f"""/* =====================================================================================
   Wraithguard's colour themes in the viewer: generated by tools/gen_viewer_themes.py from
   wraithguard/gui/theme.py's THEME_PRESETS ({len(themes)} of them) -- do not edit.

   Each is worn like the Wraithguard theme (ui/viewer_only.html derives the page from a few
   `--wg-*` colours, for `[data-theme="wraithguard"]` and every `[data-theme^="wg-"]`): a block
   of those colours per theme, and a row in Settings > Theme after the viewer's own.
   ===================================================================================== */

const WG_THEMES={data};

(function(){{
  const css=WG_THEMES.map(t=>`[data-theme="${{t.code}}"]{{${{Object.entries(t.props).map(([k,v])=>k+':'+v+';').join('')}}}}`).join('\\n');
  const el=document.createElement('style'); el.id='wg-themes'; el.textContent=css;
  document.head.appendChild(el);
  if(typeof Themes==='object') for(const t of WG_THEMES) Themes.all.push({{code:t.code, wear:t.code, label:t.label}});
}})();
"""


def main() -> int:
    """Write the file, or check it."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is out of date: run tools/gen_viewer_themes.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
